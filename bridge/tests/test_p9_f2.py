    def test_a_bzip2_session_is_read_by_MAGIC_not_by_extension(
        self, session_globals: WSClient, tmp_path
    ) -> None:
        """``cmd.file_read``'s third branch (``internal.py:305-307``).

        ``.pze``/``.pzw`` are gzip and were covered in wave 8; bzip2 has no
        session extension at all, so the only way in is ``x.pse.bz2``, and the
        only reason it works is that ``file_read`` sniffs ``BZh...1AY&SY``
        rather than trusting the name.  Proven by RENAMING the compressed file
        to a bare ``.pse``: it still loads.
        """
        ws = session_globals
        ws.call("cmd.delete", "all")
        ws.call("cmd.fragment", "trp", "p9f2bz")
        atoms = ws.call("cmd.count_atoms", "p9f2bz")

        packed = str(tmp_path / "s.pse.bz2")
        plain = str(tmp_path / "s.pse")
        ws.call("cmd.save", packed)
        ws.call("cmd.save", plain)
        with open(packed, "rb") as handle:
            magic = handle.read(10)
        assert magic[:3] == b"BZh" and magic[4:10] == b"1AY&SY", magic
        assert os.path.getsize(packed) < os.path.getsize(plain)

        ws.call("cmd.delete", "all")
        ws.call("cmd.load", packed)
        assert ws.call("cmd.get_names", "all") == ["p9f2bz"]
        assert ws.call("cmd.count_atoms", "p9f2bz") == atoms

        # The name is irrelevant; the magic is not.
        lying = str(tmp_path / "lying.pse")
        with open(packed, "rb") as src, open(lying, "wb") as dst:
            dst.write(src.read())
        ws.call("cmd.delete", "all")
        ws.call("cmd.load", lying)
        assert ws.call("cmd.get_names", "all") == ["p9f2bz"]

