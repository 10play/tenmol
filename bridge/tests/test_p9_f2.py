#: The three that raise, and the one that succeeds while writing nothing.
#: ``obj``'s emptiness is a property of the SCENE (`get_mtl_obj` serialises
#: triangles only), which is why it is a separate test rather than a refusal.
REFUSES: Dict[str, str] = {
    "gltf": "could not find collada2gltf",
    "mtl": ".MTL export not implemented",
    "stl": "STL export not supported by this PyMOL build",
}

EMPTY = {"obj"}

#: ``png`` is the only entry that needs a GL context, so it is gated and
#: asserted separately.
GL_ONLY = {"png"}


def write(ws: WSClient, fmt: str, target: str) -> Dict[str, Any]:
    """``cmd.save`` one format; report what happened, never raise."""
    selection = SELECTION_FOR.get(fmt, "all")
    reply = ws.call_reply("cmd.save", target, selection, -1)
    if reply["t"] == "err":
        return {"ok": False, "error": str(reply["error"].get("message", ""))}
    out: Dict[str, Any] = {"ok": True, "result": reply["result"], "size": -1, "head": b""}
    if os.path.exists(target):
        out["size"] = os.path.getsize(target)
        with open(target, "rb") as handle:
            out["head"] = handle.read(64)
    return out


class TestSaveRegistrySweep:
    """Row 267 — every ``save_formats()`` entry, actually written."""

    def test_the_manifest_and_the_registry_agree(self, files: WSClient) -> None:
        """``save_formats()`` must cover BOTH dispatch tables in ``cmd.save``.

        ``cmd.save`` has two: ``savefunctions`` and the local ``func_type4``
        (``exporting.py:853-857``) for the chempy writers.  ``mmod`` lives only
        in the second one and was missing from the answer, even though
        ``save_check`` calls ``x.mmod`` recognised -- the two halves of the
        service disagreed about one extension.
        """
        from pymol import exporting

        formats = files.call(NS + ".save_formats")
        assert set(formats) >= set(exporting.savefunctions), "savefunctions key lost"
        assert {"mmod", "pkl", "pkla"} <= set(formats), (
            "func_type4 is a dispatch table of cmd.save too"
        )
        # ...and nothing in the list may be an extension the picker would then
        # reject on the way out.
        for fmt in formats:
            check = files.call(NS + ".save_check", "/tmp/p9f2." + fmt)
            assert check["recognised"] is True, (fmt, check)

    def test_every_format_in_the_registry_is_written_or_refused(
        self, scene: WSClient, tmp_path
    ) -> None:
        """The sweep.  One scene, 32 targets, no format left unattempted.

        The three tables above are a RECORD OF MEASUREMENT, not a
        reimplementation: each entry is checked against the bytes this run put
        on disk, so changing a writer (or losing one) reddens the test.
        """
        ws = scene
        formats = [f for f in ws.call(NS + ".save_formats") if f not in GL_ONLY]
        assert len(formats) == 31, formats

        unattempted: List[str] = []
        for fmt in formats:
            target = str(tmp_path / ("sweep." + fmt))
            outcome = write(ws, fmt, target)

            if fmt in REFUSES:
                assert outcome["ok"] is False, (fmt, outcome)
                assert REFUSES[fmt] in outcome["error"], (fmt, outcome["error"])
            elif fmt in EMPTY:
                assert outcome["ok"] is True, (fmt, outcome)
                assert outcome["size"] == 0, (fmt, outcome)
            elif fmt in WRITES:
                want = WRITES[fmt]
                assert outcome["ok"] is True, (fmt, outcome)
                assert outcome["size"] >= want["min_size"], (fmt, outcome["size"])
                assert outcome["head"].startswith(want["head"]), (fmt, outcome["head"])
            else:
                unattempted.append(fmt)

        assert unattempted == [], (
            "a format is in save_formats() with no recorded outcome: %r" % unattempted
        )
        # Every non-refusing writer really produced a distinct file.
        written = sorted(
            name for name in os.listdir(str(tmp_path)) if name.startswith("sweep.")
        )
        assert len(written) == len(WRITES) + len(EMPTY), written

    @pytest.mark.gl
    def test_png_is_the_one_entry_that_writes_the_file_itself(
        self, scene: WSClient, gl_bridge, tmp_path
    ) -> None:
        """``cmd.save``'s signature introspection has an early return.

        ``exporting.py:895-897``: if the ``savefunctions`` entry takes a
        ``filename`` parameter, ``save`` assumes the function wrote the file
        and RETURNS ITS STATUS instead of writing anything.  ``png`` is the
        only such entry, and it is observable: every other writer makes
        ``cmd.save`` return ``None``, ``png`` makes it return ``1``.
        """
        ws = scene
        target = str(tmp_path / "sweep.png")
        outcome = write(ws, "png", target)
        assert outcome["ok"] is True, outcome
        assert outcome["result"] == 1, outcome
        assert outcome["head"].startswith(b"\x89PNG\r\n\x1a\n"), outcome["head"]
        assert outcome["size"] > 1000, outcome

        other = write(ws, "pdb", str(tmp_path / "notpng.pdb"))
        assert other["result"] is None, "only the filename-taking writers return a status"

    def test_the_unavailable_manifest_is_exactly_the_measured_failures(
        self, scene: WSClient, tmp_path
    ) -> None:
        """``SAVE_UNAVAILABLE_FORMATS`` is the client's only warning, so it is
        checked against the engine rather than against itself.

        Everything the manifest lists must really fail (or write nothing), and
        nothing it omits may fail -- otherwise the picker offers a format that
        dies at ``Save``.
        """
        ws = scene
        annotated = {
            key.lstrip("."): value
            for key, value in files_panel.SAVE_UNAVAILABLE_FORMATS.items()
        }
        broken = set()
        for fmt in ws.call(NS + ".save_formats"):
            if fmt in GL_ONLY:
                continue
            outcome = write(ws, fmt, str(tmp_path / ("m." + fmt)))
            if not outcome["ok"] or outcome["size"] == 0:
                broken.add(fmt)
        # `.glb` is annotated as an alias of gltf and is not a registry key.
        assert broken == set(annotated) - {"glb"}, (broken, sorted(annotated))
        assert broken == set(REFUSES) | EMPTY

    def test_idtf_is_a_PAIR_and_save_concatenates_it(
        self, scene: WSClient, tmp_path
    ) -> None:
        """``exporting.py:900-901`` joins a returned sequence into one file.

        ``get_idtf`` returns ``(node, resource)``.  If ``save`` wrote only
        ``contents[0]`` the file would still look like a valid IDTF header --
        so the proof is arithmetic: the file is byte-for-byte both halves.
        """
        ws = scene
        target = str(tmp_path / "pair.idtf")
        assert write(ws, "idtf", target)["ok"] is True
        parts = ws.call("cmd.get_idtf")
        blobs = parts["__blobs__"] if isinstance(parts, dict) else parts
        assert isinstance(blobs, list) and len(blobs) == 2, parts
        sizes = [int(b["size"]) for b in blobs]
        assert os.path.getsize(target) == sum(sizes), (os.path.getsize(target), sizes)
        assert min(sizes) > 0, sizes

    def test_gz_and_bz2_wrap_whatever_the_writer_returned(
        self, scene: WSClient, tmp_path
    ) -> None:
        """``exporting.py:905-919``: the compression is ``save``'s, not the
        writer's, so it applies to any string-returning format.

        Both are round-tripped through ``cmd.load``, because a compressed file
        PyMOL cannot read again would pass a magic-byte check.
        """
        ws = scene
        plain = str(tmp_path / "z.pdb")
        gz = str(tmp_path / "z.pdb.gz")
        bz2 = str(tmp_path / "z.pdb.bz2")
        for target in (plain, gz, bz2):
            ws.call("cmd.save", target, MOL, -1)

        with open(gz, "rb") as handle:
            assert handle.read(2) == b"\x1f\x8b"
        with open(bz2, "rb") as handle:
            assert handle.read(3) == b"BZh"
        assert os.path.getsize(gz) < os.path.getsize(plain)
        assert os.path.getsize(bz2) < os.path.getsize(plain)

        atoms = ws.call("cmd.count_atoms", MOL)
        for target, name in ((gz, "p9f2gz"), (bz2, "p9f2bz")):
            ws.call("cmd.load", target, name)
            assert ws.call("cmd.count_atoms", name) == atoms, target
            ws.call("cmd.delete", name)

    def test_a_names_filter_silently_writes_an_empty_session(
        self, scene: WSClient, tmp_path
    ) -> None:
        """A TRAP in ``cmd.save``, measured -- and the reason the web client's
        Save Session must keep passing no selection at all.

        For ``pse``/``psw`` the second argument is not an atom selection, it is
        the ``names`` filter of ``cmd.get_session``.  ``get_psestr``
        (``exporting.py:975-979``) drops it only when it contains a bracket, and
        ``selector.process`` leaves a bare ``all`` bare -- so
        ``cmd.save(f, 'all')`` writes a session with NO OBJECTS IN IT, returns
        success, and reloads as an empty scene.
        """
        ws = scene
        default = str(tmp_path / "full.pse")
        filtered = str(tmp_path / "filtered.pse")
        ws.call("cmd.save", default)
        ws.call("cmd.save", filtered, "all", -1)
        assert os.path.getsize(filtered) * 4 < os.path.getsize(default), (
            os.path.getsize(filtered),
            os.path.getsize(default),
        )

        before = sorted(ws.call("cmd.get_names", "all"))
        ws.call("cmd.load", filtered)
        assert ws.call("cmd.get_names", "all") == [], (
            "a names-filtered .pse restores an EMPTY scene"
        )
        ws.call("cmd.load", default)
        assert sorted(ws.call("cmd.get_names", "all")) == before

        # ...and this is exactly why the client's Save Session emits no
        # selection: `cmd.save`'s own default is `(all)`, which the bracket
        # test does catch.
        from pymol import selector

        assert "(" in selector.process("(all)") and "(" not in selector.process("all")


