    def test_session_file_is_rewritten_with_unix_separators(
        self, session_globals: WSClient, tmp_path
    ) -> None:
        """``importing.py:839-841`` / ``exporting.py:846-848``, and it BITES.

        Both halves do ``filename.replace('\\\\', '/')`` unconditionally.  On
        POSIX a backslash is an ordinary filename character, so saving to
        ``a\\b.pse`` writes ``a\\b.pse`` but records ``a/b.pse`` -- a path that
        does not exist.  Save Session (no dialog) would then write to a
        directory that is not there, which is why the client shows
        ``session_file`` rather than assuming it.
        """
        ws = session_globals
        ws.call("cmd.delete", "all")
        ws.call("cmd.fragment", "trp", "p9f2sep")
        weird = str(tmp_path / "a\\b.pse")
        ws.call("cmd.save", weird)
        assert os.path.exists(weird), "the file itself keeps the backslash"
        recorded = ws.call("cmd.get", "session_file")
        assert recorded == weird.replace("\\", "/") != weird
        assert not os.path.exists(recorded)

        ws.call("cmd.set", "session_file", "P9F2-SENTINEL")
        ws.call("cmd.delete", "all")
        ws.call("cmd.load", weird)
        assert ws.call("cmd.get", "session_file") == recorded, (
            "load_pse does the same substitution"
        )
        assert ws.call("cmd.get_names", "all") == ["p9f2sep"]
        # ...and the bridge's own answer carries the same broken path, which is
        # what the title bar shows.
        info = ws.call(NS + ".session_file")
        assert info["hasPath"] is True and info["path"] == recorded
