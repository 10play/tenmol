class TestGeometryExports:
    def test_collada_is_real_xml_with_the_scene_in_it(
        self, scene: WSClient, tmp_path
    ) -> None:
        """Row 272's gap: ``.dae`` had never been WRITTEN.

        Weighing the file would not prove much, so it is parsed: a COLLADA root
        in the 1.4.1 namespace, with the geometry and visual-scene libraries a
        consumer actually reads, and at least one ``<float_array>`` of
        coordinates.
        """
        ws = scene
        target = str(tmp_path / "geom.dae")
        assert write(ws, "dae", target)["ok"] is True
        tree = ET.parse(target)
        root = tree.getroot()
        assert root.tag == "{http://www.collada.org/2005/11/COLLADASchema}COLLADA"
        libraries = {
            child.tag.rsplit("}", 1)[-1] for child in root
        }
        assert {"library_geometries", "library_visual_scenes", "scene"} <= libraries, (
            libraries
        )
        arrays = root.findall(
            ".//{http://www.collada.org/2005/11/COLLADASchema}float_array"
        )
        assert arrays, "a COLLADA with no coordinates is not an export"
        assert int(arrays[0].get("count", "0")) > 0

    def test_the_five_menu_formats_land_on_three_writers_and_two_walls(
        self, scene: WSClient, tmp_path
    ) -> None:
        """``pymol_qt_gui.py:793-821`` offers wrl/dae/pov/stl/gltf.

        Three write; two cannot in this build, and they fail DIFFERENTLY --
        ``stl`` is Incentive-only, ``gltf`` is a missing external binary --
        which is why ``GEOMETRY_EXPORTS`` carries a per-format reason rather
        than one "not supported" string.
        """
        ws = scene
        offered = [item["format"] for item in files_panel.GEOMETRY_EXPORTS]
        assert sorted(offered) == ["dae", "gltf", "pov", "stl", "wrl"], offered
        for fmt in offered:
            outcome = write(ws, fmt, str(tmp_path / ("menu." + fmt)))
            if fmt in REFUSES:
                assert outcome["ok"] is False, fmt
            else:
                assert outcome["ok"] is True and outcome["size"] > 1000, (fmt, outcome)

    def test_obj_writes_an_empty_file_for_a_lines_only_scene(
        self, scene: WSClient, tmp_path
    ) -> None:
        """The manifest's ``.obj`` warning, proven both ways.

        ``get_mtl_obj`` serialises TRIANGLES only, and ``cmd.save`` happily
        writes the resulting empty string -- a zero-byte file and a success
        return.  Showing a surface on the same atoms turns the same call into a
        real Wavefront OBJ, which is what makes the manifest's wording ("a
        lines-only scene writes 0 bytes") the accurate one.
        """
        ws = scene
        sticks = str(tmp_path / "sticks.obj")
        assert write(ws, "obj", sticks) == {
            "ok": True,
            "result": None,
            "size": 0,
            "head": b"",
        }

        ws.call("cmd.show", "surface", "%s and resi 1-5" % MOL)
        ws.call("cmd.rebuild")
        solid = str(tmp_path / "surface.obj")
        outcome = write(ws, "obj", solid)
        ws.call("cmd.hide", "surface")
        assert outcome["ok"] is True and outcome["size"] > 1000, outcome
        with open(solid, "rb") as handle:
            body = handle.read()
        assert b"\nv " in body and b"\nf " in body, body[:200]


